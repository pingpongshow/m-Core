#!/bin/sh
# Turns AccessorySetupKit pairing on or off in the generated App/Info.plist.
#
# With MCORE_ACCESSORY_SETUP_KIT = NO the two NSAccessorySetupKit* keys are dropped, which puts the app back on plain
# CoreBluetooth: the usual Bluetooth permission prompt, and radios found by scanning rather than through the system
# accessory picker. `AccessoryPairing` reads those keys at launch and switches the app over by itself, so no Swift
# changes are needed. Worth trying when a radio pairs in Settings but the app still can't reach it: under
# AccessorySetupKit, CoreBluetooth only reports `poweredOn` once an authorized accessory is reachable, and iOS 18 had a
# bug where it never did (https://developer.apple.com/forums/thread/811101).
#
# Set it in Config/Local.xcconfig (gitignored), or in the environment for one build:
#     make build MCORE_ACCESSORY_SETUP_KIT=NO
#
# App/Info.plist is generated by XcodeGen, so `make generate` re-applies this on every build. After switching, build
# once with make (or rerun `make generate`) before building from Xcode again.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
plist="$root/App/Info.plist"

if [ ! -f "$plist" ]; then
    echo "$(basename "$0"): $plist not found; run 'make generate' first." >&2
    exit 1
fi

# Precedence: the environment, then a local override, then the checked-in default.
setting=${MCORE_ACCESSORY_SETUP_KIT:-}
if [ -z "$setting" ]; then
    for file in "$root/Config/Local.xcconfig" "$root/Config/Base.xcconfig"; do
        [ -f "$file" ] || continue
        found=$(sed -n 's|^[[:space:]]*MCORE_ACCESSORY_SETUP_KIT[[:space:]]*=[[:space:]]*\([A-Za-z0-9]*\).*|\1|p' "$file" | tail -1)
        if [ -n "$found" ]; then
            setting=$found
            break
        fi
    done
fi
[ -n "$setting" ] || setting=YES

case $(printf '%s' "$setting" | tr '[:lower:]' '[:upper:]') in
    NO|OFF|FALSE|0)
        for key in NSAccessorySetupKitSupports NSAccessorySetupBluetoothServices; do
            /usr/libexec/PlistBuddy -c "Delete :$key" "$plist" >/dev/null 2>&1 || true
        done
        echo "AccessorySetupKit: off — plain CoreBluetooth (Settings → Radio → Scan for radios)"
        ;;
    *)
        echo "AccessorySetupKit: on — system accessory picker (Settings → Radio → Add radio)"
        ;;
esac
